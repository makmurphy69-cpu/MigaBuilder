// Builds i18n/palette.js: translations for the Ctrl+K tool search and the "what next" card
// (miga-palette.js). Tool descriptions come from the homepage translations (home-i18n.js)
// when the wording is the same; the palette's own text and the few descriptions worded
// differently are in palette-i18n-extra.json next to this script.
//   node scripts/build-palette-i18n.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const LANGS = ['es', 'ar', 'zh', 'sw', 'sv', 'de', 'pt', 'fr'];

const win = {};
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'home-i18n.js'), 'utf8'), { window: win });
const HOME = win.HOME_I18N;
const extra = JSON.parse(fs.readFileSync(path.join(ROOT, 'scripts', 'palette-i18n-extra.json'), 'utf8'));
const palette = fs.readFileSync(path.join(ROOT, 'miga-palette.js'), 'utf8');
const tools = [...palette.matchAll(/\["([^"]+\.html)", "[^"]*", "[^"]+", "([^"]*)"/g)].map(m => ({ page: m[1], desc: m[2] }));

const out = {}, missing = [];
for (const t of tools) {
  const key = 'd:' + t.page.replace(/\.html$/, '');
  if (extra[t.desc]) continue;
  if (HOME.en[key] === t.desc && LANGS.every(l => HOME[l] && HOME[l][key])) out[t.desc] = Object.fromEntries(LANGS.map(l => [l, HOME[l][key]]));
  else missing.push(t.page + ': ' + t.desc);
}
for (const [en, row] of Object.entries(extra)) {
  const gaps = LANGS.filter(l => !row[l]);
  if (gaps.length) missing.push(en + ' (no ' + gaps.join(', ') + ')');
  out[en] = row;
}
const body = Object.entries(out).map(([en, row]) => '  ' + JSON.stringify(en) + ': { ' + LANGS.map(l => l + ': ' + JSON.stringify(row[l])).join(', ') + ' }').join(',\n');
fs.writeFileSync(path.join(ROOT, 'i18n', 'palette.js'), '/* Ctrl+K tool search and "what next" card — generated by scripts/build-palette-i18n.mjs, do not edit. */\nI18N.phrases({\n' + body + '\n});\n');
console.log('i18n/palette.js: ' + Object.keys(out).length + ' phrases');
if (missing.length) { console.error('Not translated:\n  ' + missing.join('\n  ')); process.exit(1); }
